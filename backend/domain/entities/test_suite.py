"""Test Suite Entity.

Encapsulates unit test assertions and adversarial Maker-Breaker challenge suites.
"""

import hashlib
from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class TestResult:
    """Individual assertion outcome from isolated test runner."""

    __test__ = False
    name: str
    passed: bool
    duration_ms: float
    error_message: Optional[str] = None


@dataclass
class TestSuite:
    """A collection of deterministic verification tests."""

    __test__ = False
    suite_id: str
    test_code: str
    is_adversarial: bool = False  # True if generated by the Maker-Breaker Adversary
    framework: str = "pytest"
    results: List[TestResult] = field(default_factory=list)

    @property
    def sha256_hash(self) -> str:
        return hashlib.sha256(self.test_code.strip().encode("utf-8")).hexdigest()

    @property
    def total_tests(self) -> int:
        return len(self.results)

    @property
    def passed_tests(self) -> int:
        return sum(1 for r in self.results if r.passed)

    @property
    def all_passed(self) -> bool:
        return self.total_tests > 0 and self.passed_tests == self.total_tests

    def record_result(self, name: str, passed: bool, duration_ms: float, error_message: Optional[str] = None):
        self.results.append(TestResult(name=name, passed=passed, duration_ms=duration_ms, error_message=error_message))
